/**
 ******************************************************************************
 * @file    comm_cfg.h
 * @brief   通信与调试的全局编译期开关（协议层与应用层共用，故放在 Utility）
 *
 * 两档工作模式：
 *
 *   ① 调试档（默认）：COMM_DEBUG_REPORT = 1
 *      · USART1 只输出人类可读文本（[DN]/[UP]/[FP]/[PR]/[ST]）
 *      · COMM_DEBUG_SILENT 默认跟随为 1：协议侧不发任何二进制帧
 *        （1 kHz 上行主动帧、参数应答全部暂停），保证串口上只有文本
 *      · 依然正常接收下行帧、维护链路计时与超时保护，控制逻辑不受影响
 *
 *   ② 交付档：COMM_DEBUG_REPORT = 0
 *      · 打印代码全部编译为空，零开销
 *      · 恢复文档规定：上行帧 1 kHz 主动上报 + 参数链路一问一答
 *
 * 只改这一个文件即可在两种模式间切换。
 ******************************************************************************
 */

#ifndef __COMM_CFG_H
#define __COMM_CFG_H

/* ===== 调试上报总开关 ===== */
#ifndef COMM_DEBUG_REPORT
#define COMM_DEBUG_REPORT 0
#endif

/* ===== 调试期协议静默 =====
 * 1 = 不发上行主动帧、不发参数应答（串口上只有文本日志）
 * 0 = 协议照常输出（此时文本会与二进制混流，仅用于对照抓包）
 * 默认跟随调试开关：调试时静默，交付时协议全开。 */
#ifndef COMM_DEBUG_SILENT
#define COMM_DEBUG_SILENT COMM_DEBUG_REPORT
#endif

#endif /* __COMM_CFG_H */
